"""
Question 8: Largest Product in a Series
URL: https://projecteuler.net/problem=8

The four adjacent digits in the 1000-digit number that have the greatest product are 9 x 9 x 8 x 9 = 5832.

Find the thirteen adjacent digits in the 1000-digit number that have the greatest product. What is the value of this product?

Measured Runtime: ~0.000942s
"""

import math
import time

NUMBER_STRING = (
    "73167176531330624919225119674426574742355349194934"
    "96983520312774506326239578318016984801869478451846"
    "43961362332117589540683537340080056970056463990666"
    "63806746816007421111624838634882195200236186835560"
    "47326848105741006198642055106198305018617882200388"
    "74744243689408611139499878239023653130541738734293"
    "55663738096232551460395726202974950346765798993856"
    "03507403487373575973549911540306129841804791530932"
    "62440656643086021394946395224737190702179860943702"
    "77053921717629317675238467481846766940513200056812"
    "71452635608277857713427577896091736371787214684409"
    "01224953430146549585371050792279689258923542019956"
    "11212902196086403441815981362977477130996051870721"
    "13499999983729780499510597317328160963185950244594"
    "55346908302642522308253344685035261931188171010003"
    "13783875288658753320838142061717766914730359825349"
    "04287554687311595628638823537875937519577818577805"
    "32171226806613001927876611195909216420198938095257"
    "20106548586327886593615338182796823030195203530185"
    "29689957736225994138912497217752834791315155748572"
)


def solve(n: int = 13) -> int:
    highest_product = 0
    for i in range(0, len(NUMBER_STRING) - n + 1):
        sliced_chars = NUMBER_STRING[i : i + n]
        digits = [int(char) for char in sliced_chars]
        product = math.prod(digits)
        if product > highest_product:
            highest_product = product
    return highest_product


if __name__ == "__main__":
    start_time = time.perf_counter()
    answer = solve()
    elapsed = time.perf_counter() - start_time

    print(f"Answer: {answer}")
    print(f"Execution Time: {elapsed:.6f} seconds")
